fn popup_js(_endpoints: &[ApiEndpoint]) -> String {
    String::from(
        "// Auto-generated by Flux API Builder — popup controller.\n\
         const out = document.getElementById(\"out\");\n\
         const tokenEl = document.getElementById(\"token\");\n\
         chrome.storage.local.get(\"token\").then(s => { if (s.token) tokenEl.value = s.token; });\n\
         document.getElementById(\"save\").onclick = () => chrome.storage.local.set({ token: tokenEl.value || null }).then(() => { out.textContent = \"token saved\"; });\n\
         const list = document.getElementById(\"list\");\n\
         for (const ep of globalThis.FLUX_ENDPOINTS) {\n\
         \x20 const row = document.createElement(\"div\"); row.className = \"ep\";\n\
         \x20 const v = document.createElement(\"span\"); v.className = \"verb \" + ep.verb; v.textContent = ep.verb; row.appendChild(v);\n\
         \x20 const o = document.createElement(\"span\"); o.className = \"op\"; o.title = ep.summary || ep.path; o.textContent = ep.path; row.appendChild(o);\n\
         \x20 const b = document.createElement(\"button\"); b.textContent = \"call\";\n\
         \x20 b.onclick = () => { out.textContent = \"…\"; chrome.runtime.sendMessage({ type: \"flux-call\", client: ep.client, method: ep.method, opts: {} }, (r) => { out.textContent = r && r.ok ? JSON.stringify(r.res, null, 2) : (\"error: \" + (r ? r.error : \"no response\")); }); };\n\
         \x20 row.appendChild(b); list.appendChild(row);\n\
         }\n",
    )
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::middleware::MiddlewareSpec;
    use crate::schema::{ApiEndpoint, ApiResponse, HttpMethod};
    use serde_json::Value;

    fn ep(op: &str, method: HttpMethod, path: &str, tag: &str, mw: Option<MiddlewareSpec>) -> ApiEndpoint {
        ApiEndpoint {
            crate_name: "demo".into(),
            method,
            path: path.into(),
            operation_id: op.into(),
            summary: "demo op".into(),
            parameters: vec![],
            request_body: None,
            responses: vec![ApiResponse { status: 200, description: "".into(), schema: None }],
            tags: vec![tag.into()],
            middleware: mw,
        }
    }

    fn sample() -> Vec<ApiEndpoint> {
        vec![
            ep("list_pools", HttpMethod::GET, "/v1/pools", "dex", None),
            ep("get_pool", HttpMethod::GET, "/v1/pools/{id}", "dex", None),
            ep("submit_share", HttpMethod::POST, "/v1/share", "mining", Some(MiddlewareSpec::bearer_auth())),
        ]
    }

    #[test]
    fn bundle_has_all_mv3_files() {
        let b = generate_chrome_extension(&sample(), "https://sigilgraph.quillon.xyz", "SIGIL");
        for f in ["manifest.json", "flux-client.js", "background.js", "popup.html", "popup.js"] {
            assert!(b.file(f).is_some(), "missing {f}");
        }
    }

    #[test]
    fn manifest_is_valid_mv3_with_scoped_origin() {
        let b = generate_chrome_extension(&sample(), "https://sigilgraph.quillon.xyz/api", "SIGIL");
        let m: Value = serde_json::from_str(b.file("manifest.json").unwrap()).expect("manifest is valid JSON");
        assert_eq!(m["manifest_version"], 3);
        assert_eq!(m["background"]["service_worker"], "background.js");
        assert_eq!(m["action"]["default_popup"], "popup.html");
        let origins = m["host_permissions"].as_array().unwrap();
        assert_eq!(origins[0], "https://sigilgraph.quillon.xyz/*", "origin must be scoped to the API host");
    }

    #[test]
    fn client_emits_class_per_tag_and_method_per_op() {
        let js = client_js(&sample(), "https://api");
        assert!(js.contains("class DexClient"));
        assert!(js.contains("class MiningClient"));
        assert!(js.contains("async listPools(opts = {})"));
        assert!(js.contains("async getPool(opts = {})"));
        assert!(js.contains("async submitShare(opts = {})"));
        // path-param substitution + catalogue
        assert!(js.contains("/v1/pools/{id}"));
        assert!(js.contains("FLUX_ENDPOINTS"));
    }

    #[test]
    fn bearer_tag_attaches_authorization_header() {
        let js = client_js(&sample(), "https://api");
        // mining tag has bearer middleware → its client injects the header
        assert!(js.contains("Authorization"));
        assert!(js.contains("\"Bearer \" + token"));
    }

    #[test]
    fn service_worker_wires_messaging() {
        let b = generate_chrome_extension(&sample(), "https://api", "SIGIL");
        let bg = b.file("background.js").unwrap();
        assert!(bg.contains("importScripts(\"flux-client.js\")"));
        assert!(bg.contains("chrome.runtime.onMessage.addListener"));
        assert!(bg.contains("flux-call"));
    }
}
