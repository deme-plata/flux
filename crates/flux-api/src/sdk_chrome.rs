// Chrome extension (Manifest V3) target generator.
//
// v0.16 (rocky 2026-05-31): a new emit target alongside the language SDKs. Where
// `sdk_ts`/`sdk_python`/… emit a library you import, this emits a *complete,
// installable* MV3 Chrome extension that wraps the same API surface:
//   • manifest.json    — MV3 manifest, host_permissions scoped to the API origin
//   • flux-client.js   — vanilla-JS client (one class per tag, one method per
//                        operation) — the SDK, but runnable in a service worker
//   • background.js     — service worker that exposes the client over
//                        chrome.runtime messaging (popup/content → API)
//   • popup.html/.js    — a themed popup that lists every endpoint, holds a
//                        bearer token in chrome.storage, and renders responses
//
// Bearer auth is honored exactly like the TS SDK: when a tag's endpoints carry an
// active `AuthKind::Bearer` middleware, the client reads a token (from the call
// opts or the stored token) and attaches `Authorization: Bearer …`.

use crate::casing::{camel_case, pascal_case};
use crate::middleware::AuthKind;
use crate::schema::ApiEndpoint;

/// A generated Chrome extension as a set of (filename, content) files. Write each
/// to a directory and `chrome://extensions → Load unpacked` points at it.
#[derive(Debug, Clone)]
pub struct ChromeExtensionBundle {
    pub files: Vec<(String, String)>,
}

impl ChromeExtensionBundle {
    /// Look up one emitted file's content by name.
    pub fn file(&self, name: &str) -> Option<&str> {
        self.files.iter().find(|(n, _)| n == name).map(|(_, c)| c.as_str())
    }
}

/// Derive an MV3 `host_permissions` origin pattern (`scheme://host/*`) from a base URL.
fn origin_pattern(base_url: &str) -> String {
    let (scheme, rest) = base_url.split_once("://").unwrap_or(("https", base_url));
    let host = rest.split(['/', '?', '#']).next().unwrap_or(rest);
    format!("{scheme}://{host}/*")
}

/// Generate a complete MV3 Chrome extension for the given API surface.
pub fn generate_chrome_extension(
    endpoints: &[ApiEndpoint],
    base_url: &str,
    name: &str,
) -> ChromeExtensionBundle {
    let files = vec![
        ("manifest.json".to_string(), manifest(base_url, name)),
        ("flux-client.js".to_string(), client_js(endpoints, base_url)),
        ("background.js".to_string(), background_js(endpoints)),
        ("popup.html".to_string(), popup_html(name)),
        ("popup.js".to_string(), popup_js(endpoints)),
    ];
    ChromeExtensionBundle { files }
}

fn manifest(base_url: &str, name: &str) -> String {
    // Hand-built so the output is byte-stable and obviously MV3-correct.
    format!(
        "{{\n  \"manifest_version\": 3,\n  \"name\": \"{name} API\",\n  \"version\": \"0.1.0\",\n  \"description\": \"Auto-generated by Flux API Builder — Chrome extension for {name}.\",\n  \"permissions\": [\"storage\"],\n  \"host_permissions\": [\"{origin}\"],\n  \"background\": {{ \"service_worker\": \"background.js\" }},\n  \"action\": {{ \"default_popup\": \"popup.html\", \"default_title\": \"{name} API\" }}\n}}\n",
        name = name,
        origin = origin_pattern(base_url),
    )
}

/// Group endpoints by tag (BTreeSet for stable order), as the TS SDK does.
fn tags_of(endpoints: &[ApiEndpoint]) -> Vec<String> {
    endpoints
        .iter()
        .flat_map(|e| e.tags.clone())
        .collect::<std::collections::BTreeSet<_>>()
        .into_iter()
        .collect()
}

fn client_js(endpoints: &[ApiEndpoint], base_url: &str) -> String {
    let mut s = String::from(
        "// Auto-generated by Flux API Builder — Chrome MV3 client.\n// Runs in the service worker and the popup. No bundler required.\n",
    );
    for tag in tags_of(endpoints) {
        let eps: Vec<_> = endpoints.iter().filter(|e| e.tags.contains(&tag)).collect();
        if eps.is_empty() {
            continue;
        }
        let cn = pascal_case(&tag.replace('-', "_"));
        let bearer = eps
            .iter()
            .any(|e| e.middleware.as_ref().is_some_and(|m| m.is_active() && matches!(m.auth, AuthKind::Bearer)));

        s.push_str(&format!("class {cn}Client {{\n"));
        s.push_str(&format!(
            "  constructor(baseUrl = \"{base_url}\", token = null) {{ this.baseUrl = baseUrl; this.token = token; }}\n"
        ));
        // shared request helper — path params, query, JSON body, bearer header
        s.push_str("  async _req(method, template, opts = {}) {\n");
        s.push_str("    const path = template.replace(/\\{(\\w+)\\}/g, (_, k) => encodeURIComponent((opts.path || {})[k]));\n");
        s.push_str("    const url = new URL(this.baseUrl + path);\n");
        s.push_str("    for (const [k, v] of Object.entries(opts.query || {})) url.searchParams.set(k, v);\n");
        s.push_str("    const headers = { \"Content-Type\": \"application/json\" };\n");
        if bearer {
            s.push_str("    const token = opts.token ?? this.token;\n");
            s.push_str("    if (token) headers[\"Authorization\"] = \"Bearer \" + token;\n");
        }
        s.push_str("    const init = { method, headers };\n");
        s.push_str("    if (opts.body !== undefined) init.body = JSON.stringify(opts.body);\n");
        s.push_str("    const r = await fetch(url, init);\n");
        s.push_str("    const text = await r.text();\n");
        s.push_str("    try { return { status: r.status, body: JSON.parse(text) }; } catch { return { status: r.status, body: text }; }\n");
        s.push_str("  }\n");
        for ep in &eps {
            let mn = camel_case(&ep.operation_id);
            let verb = format!("{:?}", ep.method).to_uppercase();
            s.push_str(&format!(
                "  async {mn}(opts = {{}}) {{ return this._req(\"{verb}\", \"{}\", opts); }}\n",
                ep.path
            ));
        }
        s.push_str("}\n");
    }
    // expose every client + an endpoint catalogue on the global scope so the
    // service worker (importScripts) and popup can both reach them.
    s.push_str("\nconst FLUX_CLIENTS = {");
    for tag in tags_of(endpoints) {
        let cn = pascal_case(&tag.replace('-', "_"));
        s.push_str(&format!(" \"{cn}\": {cn}Client,"));
    }
    s.push_str(" };\n");
    s.push_str("const FLUX_ENDPOINTS = [\n");
    for ep in endpoints {
        let tag = ep.tags.first().cloned().unwrap_or_default();
        let cn = pascal_case(&tag.replace('-', "_"));
        s.push_str(&format!(
            "  {{ client: \"{cn}\", method: \"{}\", verb: \"{}\", op: \"{}\", path: \"{}\", summary: \"{}\" }},\n",
            camel_case(&ep.operation_id),
            format!("{:?}", ep.method).to_uppercase(),
            ep.operation_id,
            ep.path,
            ep.summary.replace('"', "'"),
        ));
    }
    s.push_str("];\n");
    s.push_str("if (typeof globalThis !== \"undefined\") { globalThis.FLUX_CLIENTS = FLUX_CLIENTS; globalThis.FLUX_ENDPOINTS = FLUX_ENDPOINTS; }\n");
    s
}

fn background_js(_endpoints: &[ApiEndpoint]) -> String {
    // Service worker: load the client, answer call requests over messaging.
    String::from(
        "// Auto-generated by Flux API Builder — MV3 service worker.\n\
         importScripts(\"flux-client.js\");\n\
         \n\
         chrome.runtime.onMessage.addListener((msg, _sender, sendResponse) => {\n\
         \x20 if (msg?.type !== \"flux-call\") return false;\n\
         \x20 (async () => {\n\
         \x20\x20\x20 try {\n\
         \x20\x20\x20\x20\x20 const { client, method, opts } = msg;\n\
         \x20\x20\x20\x20\x20 const stored = await chrome.storage.local.get(\"token\");\n\
         \x20\x20\x20\x20\x20 const Ctor = globalThis.FLUX_CLIENTS[client];\n\
         \x20\x20\x20\x20\x20 if (!Ctor) throw new Error(\"unknown client: \" + client);\n\
         \x20\x20\x20\x20\x20 const c = new Ctor(undefined, stored.token ?? null);\n\
         \x20\x20\x20\x20\x20 const res = await c[method](opts || {});\n\
         \x20\x20\x20\x20\x20 sendResponse({ ok: true, res });\n\
         \x20\x20\x20 } catch (e) {\n\
         \x20\x20\x20\x20\x20 sendResponse({ ok: false, error: String(e) });\n\
         \x20\x20\x20 }\n\
         \x20 })();\n\
         \x20 return true; // async response\n\
         });\n",
    )
}

